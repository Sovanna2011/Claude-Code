#!/usr/bin/env python3
"""Generate EF Core entities and configurations for the S/4HANA-inspired ERP.

Source of truth: docs/s4hana/table_catalogue.csv (same model the DDL uses).
Output: backend/ErpS4.Database/{Entities,Configurations}/*.cs and the DbContext
        DbSet partial.

    python3 tools/generate_ef_core.py
"""

from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from catalogue_model import (  # noqa: E402
    DECIMAL,
    NVARCHAR,
    ROOT,
    SCHEMA_ORDER,
    Field,
    Table,
    load_tables,
    resolve_foreign_keys,
)

PROJECT = ROOT / "backend" / "ErpS4.Database"
ENTITIES = PROJECT / "Entities"
CONFIGURATIONS = PROJECT / "Configurations"

SCHEMA_TITLES = {
    "org": "Enterprise structure",
    "cfg": "Configuration, data dictionary and custom objects",
    "mdm": "Business Partner and master data",
    "fin": "Financial accounting and asset accounting",
    "co": "Controlling",
    "wf": "Workflow and approval",
    "sec": "Users and security",
    "audit": "Audit and change documents",
    "rpt": "Reporting metadata",
    "intg": "Integration and API management",
}

CSHARP_KEYWORDS = {
    "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char",
    "checked", "class", "const", "continue", "decimal", "default", "delegate",
    "do", "double", "else", "enum", "event", "explicit", "extern", "false",
    "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit",
    "in", "int", "interface", "internal", "is", "lock", "long", "namespace",
    "new", "null", "object", "operator", "out", "override", "params",
    "private", "protected", "public", "readonly", "ref", "return", "sbyte",
    "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct",
    "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong",
    "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile",
    "while",
}

HEADER = """// <auto-generated>
//     Generated from docs/s4hana/table_catalogue.csv.
//     Regenerate: python3 tools/generate_ef_core.py
//     Do not edit by hand - changes are overwritten.
// </auto-generated>
"""


def doc(text: str) -> str:
    return (
        text.replace("`", "")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .strip()
    )


def property_name(table: Table, field: Field) -> str:
    """C# property name for a column. A property may not carry the name of its
    own class, and may not be a keyword."""
    name = field.name
    if name == table.clr_name:
        if name.endswith("Code"):
            name += "Key"
        elif name.endswith("Key"):
            name += "Code"
        else:
            name += "Code"
        while any(f.name == name for f in table.fields):
            name += "Value"
    if name in CSHARP_KEYWORDS:  # case sensitive: "Operator" is not a keyword
        name = "@" + name
    return name


def property_map(table: Table) -> dict[str, str]:
    return {f.name: property_name(table, f) for f in table.fields}


def entity_class(table: Table) -> str:
    names = property_map(table)
    interfaces = ["ITenantScoped"] if table.has_tenant else []
    if table.is_append_only:
        interfaces.append("IAppendOnly")
    implements = f" : {', '.join(interfaces)}" if interfaces else ""

    summary = doc(table.description)
    if table.sap_reference:
        summary += f" (SAP reference: {doc(table.sap_reference)})"

    lines = [
        f"/// <summary>{summary}</summary>",
        f"/// <remarks>Table <c>{table.full_name}</c>.</remarks>",
        f"public class {table.clr_name}{implements}",
        "{",
    ]
    for f in table.fields:
        description = doc(f.description)
        if description:
            lines.append(f"    /// <summary>{description}</summary>")
        initializer = ""
        if f.clr_type in ("string", "byte[]") and not f.nullable:
            initializer = " = null!;"
        lines.append(
            f"    public {f.clr_type} {names[f.name]} {{ get; set; }}{initializer}"
        )
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    return "\n".join(lines)


def property_configuration(table: Table, f: Field, name: str) -> str:
    calls: list[str] = []
    if name.lstrip("@") != f.name:
        calls.append(f'HasColumnName("{f.name}")')

    if f.sql_type == "rowversion":
        calls.append("IsRowVersion()")
    elif f.sql_type == "nvarchar(max)":
        calls.append('HasColumnType("nvarchar(max)")')
    elif NVARCHAR.match(f.sql_type):
        calls.append(f"HasMaxLength({f.max_length})")
        calls.append("IsUnicode()")
    elif DECIMAL.match(f.sql_type):
        match = DECIMAL.match(f.sql_type)
        calls.append(f"HasPrecision({match.group('p')}, {match.group('s')})")  # type: ignore[union-attr]
    elif f.sql_type in ("date", "time(0)", "datetime2(3)"):
        calls.append(f'HasColumnType("{f.sql_type}")')

    if not f.nullable and f.sql_type != "rowversion":
        calls.append("IsRequired()")

    if f.is_pk and f.name == "Id":
        calls.append("ValueGeneratedOnAdd()")
    elif f.name == "CreatedAt" and not f.nullable:
        calls.append('HasDefaultValueSql("SYSUTCDATETIME()")')

    if not calls:
        return ""
    chain = ".".join(calls)
    return f"        builder.Property(e => e.{name}).{chain};"


def configuration_class(table: Table, foreign_keys: list) -> str:
    names = property_map(table)
    lines = [
        f"/// <summary>Maps <see cref=\"{table.clr_name}\"/> to "
        f"<c>{table.full_name}</c>.</summary>",
        f"public sealed class {table.clr_name}Configuration "
        f": IEntityTypeConfiguration<{table.clr_name}>",
        "{",
        f"    public void Configure(EntityTypeBuilder<{table.clr_name}> builder)",
        "    {",
        f'        builder.ToTable("{table.name}", "{table.schema}");',
    ]

    pk = table.primary_key
    if len(pk) == 1:
        lines.append(f"        builder.HasKey(e => e.{names[pk[0].name]});")
    else:
        keys = ", ".join(f"e.{names[f.name]}" for f in pk)
        lines.append(f"        builder.HasKey(e => new {{ {keys} }});")
    lines.append("")

    for f in table.fields:
        configuration = property_configuration(table, f, names[f.name])
        if configuration:
            lines.append(configuration)

    ak = table.alternate_key
    if ak:
        lines.append("")
        if len(ak) == 1:
            columns = f"e.{names[ak[0].name]}"
        else:
            columns = "new { " + ", ".join(f"e.{names[f.name]}" for f in ak) + " }"
        lines.append(
            f"        builder.HasIndex(e => {columns})\n"
            f"               .IsUnique()\n"
            f'               .HasDatabaseName("UQ_{table.schema}_{table.name}");'
        )

    indexed = [f for f in table.fields if f.is_indexed and f.name != "TenantId"]
    if indexed:
        lines.append("")
    for f in indexed:
        if table.has_tenant:
            columns = f"new {{ e.TenantId, e.{names[f.name]} }}"
        else:
            columns = f"e.{names[f.name]}"
        lines.append(
            f"        builder.HasIndex(e => {columns})\n"
            f'               .HasDatabaseName("IX_{table.schema}_{table.name}_{f.name}");'
        )

    table_keys = [
        fk
        for fk in foreign_keys
        if fk.table.full_name == table.full_name and not fk.is_code_key
    ]
    if table_keys:
        lines.append("")
    for fk in table_keys:
        target = fk.target_table
        column = names[fk.columns[0]]
        lines.append(
            f"        builder.HasOne<{target}>()\n"
            f"               .WithMany()\n"
            f"               .HasForeignKey(e => e.{column})\n"
            f"               .OnDelete(DeleteBehavior.Restrict)\n"
            f'               .HasConstraintName("{fk.name}");'
        )

    lines.extend(["    }", "}"])
    return "\n".join(lines)


def write_entities(tables: list[Table]) -> None:
    ENTITIES.mkdir(parents=True, exist_ok=True)
    for schema in SCHEMA_ORDER:
        schema_tables = [t for t in tables if t.schema == schema]
        body = "\n\n".join(entity_class(t) for t in schema_tables)
        content = (
            f"{HEADER}\n"
            f"namespace ErpS4.Database.Entities;\n\n"
            f"// {SCHEMA_TITLES[schema]} - schema [{schema}], "
            f"{len(schema_tables)} tables.\n\n"
            f"{body}\n"
        )
        (ENTITIES / f"{schema.capitalize()}Entities.cs").write_text(
            content, encoding="utf-8"
        )


def write_configurations(tables: list[Table], foreign_keys: list) -> None:
    CONFIGURATIONS.mkdir(parents=True, exist_ok=True)
    for schema in SCHEMA_ORDER:
        schema_tables = [t for t in tables if t.schema == schema]
        body = "\n\n".join(configuration_class(t, foreign_keys) for t in schema_tables)
        content = (
            f"{HEADER}\n"
            f"using ErpS4.Database.Entities;\n"
            f"using Microsoft.EntityFrameworkCore;\n"
            f"using Microsoft.EntityFrameworkCore.Metadata.Builders;\n\n"
            f"namespace ErpS4.Database.Configurations;\n\n"
            f"// {SCHEMA_TITLES[schema]} - schema [{schema}].\n\n"
            f"{body}\n"
        )
        (CONFIGURATIONS / f"{schema.capitalize()}Configurations.cs").write_text(
            content, encoding="utf-8"
        )


def write_db_sets(tables: list[Table]) -> None:
    lines = [
        HEADER,
        "using ErpS4.Database.Entities;",
        "using Microsoft.EntityFrameworkCore;",
        "",
        "namespace ErpS4.Database;",
        "",
        "public sealed partial class ErpDbContext",
        "{",
    ]
    current = None
    for table in tables:
        if table.schema != current:
            current = table.schema
            lines.append(f"    // ---- {SCHEMA_TITLES[current]} [{current}] ----")
        lines.append(
            f"    /// <summary>{doc(table.description)}</summary>\n"
            f"    public DbSet<{table.clr_name}> {table.clr_name} => "
            f"Set<{table.clr_name}>();"
        )
    lines.extend(["}", ""])
    (PROJECT / "ErpDbContext.Sets.cs").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    tables = load_tables()
    foreign_keys, _ = resolve_foreign_keys(tables)
    write_entities(tables)
    write_configurations(tables, foreign_keys)
    write_db_sets(tables)

    renamed = [
        (t.full_name, f.name, property_name(t, f))
        for t in tables
        for f in t.fields
        if property_name(t, f) != f.name
    ]
    print(
        f"backend/ErpS4.Database: {len(tables)} entities, "
        f"{sum(len(t.fields) for t in tables)} properties, "
        f"{sum(1 for f in foreign_keys if not f.is_code_key)} relationships"
    )
    print(f"  properties renamed to avoid clashing with their class: {len(renamed)}")
    for full_name, column, name in renamed:
        print(f"    {full_name}.{column} -> {name}")


if __name__ == "__main__":
    main()
