// Package report renders tabular reports to CSV, Excel and PDF.
//
// The writers are dependency free: an .xlsx file is a zip of XML parts and a
// PDF is a small set of objects with a cross-reference table, both of which are
// specified formats that can be produced from the standard library. That keeps
// the on-premises deployment free of third-party licence questions and keeps
// the container small.
package report

import (
	"fmt"
	"strings"
	"time"

	"github.com/kss/sugarplan/internal/domain"
)

// Alignment controls how a column is rendered.
type Alignment string

const (
	AlignLeft   Alignment = "left"
	AlignRight  Alignment = "right"
	AlignCentre Alignment = "centre"
)

// Column describes one column of a report.
type Column struct {
	Header string
	// Width is a hint in characters, used by Excel and PDF layout.
	Width int
	Align Alignment
	// Numeric marks a column whose cells should be written as numbers rather
	// than text, so Excel can total them.
	Numeric bool
}

// Cell is one value. Keeping the type explicit avoids guessing at render time.
type Cell struct {
	Text   string
	Number *domain.Dec
}

// Text builds a text cell.
func Text(s string) Cell { return Cell{Text: s} }

// Num builds a numeric cell, formatted with the given number of decimals.
func Num(d domain.Dec, decimals int32) Cell {
	rounded := d.Round(decimals)
	return Cell{Text: rounded.StringFixed(decimals), Number: &rounded}
}

// Date builds a date cell.
func Date(d domain.BusinessDate) Cell { return Cell{Text: string(d)} }

// Table is a rendered report: metadata, columns and rows.
//
// The metadata is what makes an exported file defensible months later: which
// company, factory, season and plan version it came from, which filters were
// applied, who generated it and when.
type Table struct {
	Code        string
	Title       string
	Company     string
	Factory     string
	Season      string
	PlanVersion string
	GeneratedAt time.Time
	GeneratedBy string
	Filters     []Filter
	Columns     []Column
	Rows        [][]Cell
	// Totals is an optional footer row.
	Totals []Cell
	// Notes appear under the table, for tolerance statements and caveats.
	Notes []string
}

// Filter is one applied filter, preserved in every export.
type Filter struct {
	Label string
	Value string
}

// MetadataLines renders the report header as text lines, shared by all three
// output formats so an Excel export and a PDF of the same report carry
// identical provenance.
func (t Table) MetadataLines() []string {
	lines := []string{}
	add := func(label, value string) {
		if value != "" {
			lines = append(lines, label+": "+value)
		}
	}
	add("Company", t.Company)
	add("Factory", t.Factory)
	add("Season", t.Season)
	add("Plan version", t.PlanVersion)
	for _, f := range t.Filters {
		add(f.Label, f.Value)
	}
	generated := t.GeneratedAt
	if generated.IsZero() {
		generated = time.Now().UTC()
	}
	add("Generated at", generated.Format("2006-01-02 15:04:05 MST"))
	add("Generated by", t.GeneratedBy)
	return lines
}

// FileName builds a safe download name for the report.
func (t Table) FileName(extension string) string {
	base := t.Code
	if base == "" {
		base = "report"
	}
	stamp := t.GeneratedAt
	if stamp.IsZero() {
		stamp = time.Now().UTC()
	}
	name := fmt.Sprintf("%s_%s.%s", base, stamp.Format("20060102_150405"), extension)
	return strings.Map(func(r rune) rune {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9',
			r == '_', r == '-', r == '.':
			return r
		default:
			return '_'
		}
	}, name)
}
