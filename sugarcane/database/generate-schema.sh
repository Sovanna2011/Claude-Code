#!/usr/bin/env bash
#
# Regenerates database/01_schema.sql from the EF Core migrations.
#
# The generated script contains filtered indexes (ASP.NET Core Identity's unique
# indexes and our own unique indexes on nullable columns). SQL Server refuses to
# create those unless QUOTED_IDENTIFIER is ON, and sqlcmd connects with it OFF,
# so the header below is prepended to every regeneration. Without it the script
# fails on the first CREATE INDEX with "Msg 1934".
#
# Usage: database/generate-schema.sh
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
output="$root/database/01_schema.sql"
body="$(mktemp)"
trap 'rm -f "$body"' EXIT

dotnet ef migrations script \
    --project "$root/src/SugarcanePlanning.Infrastructure" \
    --startup-project "$root/src/SugarcanePlanning.Api" \
    --idempotent \
    --output "$body"

{
    printf -- '-- Sugarcane Planting Planning Management System — SQL Server schema.\n'
    printf -- '-- Generated by database/generate-schema.sh from the EF Core migrations; do not edit by hand.\n'
    printf -- '--\n'
    printf -- '-- Idempotent: every object is guarded, so the script is safe to re-run.\n'
    printf -- '-- The SET options are required — filtered indexes cannot be created while\n'
    printf -- '-- QUOTED_IDENTIFIER is OFF, which is how sqlcmd connects by default.\n'
    printf -- 'SET ANSI_NULLS ON;\n'
    printf -- 'SET QUOTED_IDENTIFIER ON;\n'
    printf -- 'GO\n\n'
    # Strip the UTF-8 BOM the generator emits; it upsets some SQL clients.
    sed '1s/^\xEF\xBB\xBF//' "$body"
} > "$output"

echo "Wrote $output ($(grep -c 'CREATE TABLE' "$output") tables)."
